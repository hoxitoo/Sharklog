// Turns the author's adaptive SVG kit (adaptive/**.svg, 48×48) into
// apps/mobile/src/components/icons/glyphs.ts — shapes plus the role of each
// colour, so the app paints them from the live theme.
//
//   node docs/design/icons/build-glyphs.cjs
//
// The kit colours shapes with CSS variables (--sl-icon-body / -accent /
// -support), which react-native-svg cannot read; here each becomes a role the
// app's AppIcon resolves at render. Only path, circle and ellipse are expected —
// anything else fails the build rather than silently dropping out of a glyph.
//
// The whole kit lives here, but the app is built from adaptive/ only: themes/
// and the sprite are the same shapes in fixed colours, for Figma and the web.
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, 'adaptive');
const OUT = path.join(__dirname, '../../../apps/mobile/src/components/icons/glyphs.ts');

// Kit file → glyph name in the app (Sport / EsportsDiscipline keys behind them).
const NAMES = {
  'menu/bets': 'bets', 'menu/dashboard': 'dashboard', 'menu/insights': 'insights',
  'menu/analytics': 'analytics', 'menu/discipline': 'discipline', 'menu/settings': 'settings',
  'menu/bankroll': 'bankroll', 'menu/strategy-builder': 'strategy', 'menu/partners': 'partners',
  'menu/support-author': 'support',
  'sports/football': 'sport_football', 'sports/hockey': 'sport_hockey', 'sports/basketball': 'sport_basketball',
  'sports/tennis': 'sport_tennis', 'sports/esports': 'sport_esports', 'sports/volleyball': 'sport_volleyball',
  'sports/baseball': 'sport_baseball', 'sports/other-sport': 'sport_other',
  'esports/dota-2': 'esp_dota2', 'esports/cs2': 'esp_csgo', 'esports/league-of-legends': 'esp_lol',
  'esports/valorant': 'esp_valorant', 'esports/pubg': 'esp_pubg', 'esports/rainbow-six': 'esp_r6',
  'esports/apex-legends': 'esp_apex', 'esports/other-esport': 'esp_other',
};

function paint(v, file) {
  if (v === 'none') return 'none';
  const m = /^var\(--sl-icon-(body|accent|support)\b/.exec(v);
  if (!m) throw new Error(`${file}: unexpected colour ${v}`);
  return m[1];
}

// Everything the generated shape carries. Any other attribute — transform,
// opacity, dasharray, clip-rule… — would be dropped and the glyph would render
// wrong with no error, so it fails the build instead.
const COMMON = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'fill-rule'];
const OWN = { path: ['d'], circle: ['cx', 'cy', 'r'], ellipse: ['cx', 'cy', 'rx', 'ry'] };

function attrs(tag) {
  const out = {};
  for (const [, k, v] of tag.matchAll(/([a-z-]+)="([^"]*)"/g)) out[k] = v;
  return out;
}

const glyphs = {};
for (const [rel, name] of Object.entries(NAMES)) {
  const file = path.join(DIR, `${rel}.svg`);
  const svg = fs.readFileSync(file, 'utf8');
  if (!/viewBox="0 0 48 48"/.test(svg)) throw new Error(`${rel}: not a 48×48 viewBox`);
  const shapes = [];
  for (const [, kind, body] of svg.matchAll(/<(\w+)\b([^>]*?)\/?>/g)) {
    if (kind === 'svg' || kind === 'title') continue;
    if (!['path', 'circle', 'ellipse'].includes(kind)) throw new Error(`${rel}: unexpected <${kind}>`);
    const a = attrs(body);
    for (const k of Object.keys(a)) {
      if (!COMMON.includes(k) && !OWN[kind].includes(k)) throw new Error(`${rel}: <${kind}> ${k}="${a[k]}" is not supported`);
    }
    for (const k of OWN[kind]) if (a[k] === undefined) throw new Error(`${rel}: <${kind}> without ${k}`);
    // SVG's default fill is black, which no theme role means: say it.
    if (a.fill === undefined) throw new Error(`${rel}: <${kind}> without an explicit fill`);
    const s = { kind, fill: paint(a.fill, rel) };
    if (kind === 'path') s.d = a.d;
    else { s.cx = +a.cx; s.cy = +a.cy; if (kind === 'circle') s.r = +a.r; else { s.rx = +a.rx; s.ry = +a.ry; } }
    if (a.stroke) {
      if (a['stroke-width'] === undefined) throw new Error(`${rel}: stroke without stroke-width`);
      s.stroke = paint(a.stroke, rel); s.strokeWidth = +a['stroke-width'];
    }
    // One flag carries both: caps and joins are either both round or both default.
    const cap = a['stroke-linecap'], join = a['stroke-linejoin'];
    if ((cap ?? 'round') !== 'round' || (join ?? 'round') !== 'round' || (cap === undefined) !== (join === undefined)) {
      throw new Error(`${rel}: stroke-linecap="${cap}" stroke-linejoin="${join}" — only both round, or neither`);
    }
    if (cap === 'round') s.round = true;
    if (a['fill-rule'] !== undefined && a['fill-rule'] !== 'evenodd' && a['fill-rule'] !== 'nonzero') {
      throw new Error(`${rel}: fill-rule="${a['fill-rule']}"`);
    }
    if (a['fill-rule'] === 'evenodd') s.evenOdd = true;
    shapes.push(s);
  }
  if (!shapes.length) throw new Error(`${rel}: no shapes`);
  glyphs[name] = shapes;
}

const lit = (v) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
let ts = `// GENERATED by docs/design/icons/build-glyphs.cjs from the author's SVG kit in
// docs/design/icons/adaptive — do not edit by hand; change the SVG and regenerate.
//
// All glyphs share a 48×48 box. Each shape names the ROLE of its colour, not a
// colour: \`body\` (the silhouette), \`accent\` (the brand detail), \`support\`
// (the heart). AppIcon resolves the roles from the live theme at render time,
// so one set of shapes serves all four palettes.

export type Paint = 'body' | 'accent' | 'support' | 'none';

export interface Shape {
  kind: 'path' | 'circle' | 'ellipse';
  d?: string;
  cx?: number; cy?: number; r?: number; rx?: number; ry?: number;
  fill: Paint;
  stroke?: Paint;
  strokeWidth?: number;
  /** Round caps and joins on a stroked shape. */
  round?: boolean;
  evenOdd?: boolean;
}

export const GLYPH_BOX = 48;

export const GLYPHS = {
`;
for (const [name, shapes] of Object.entries(glyphs)) {
  ts += `  ${name}: [\n`;
  for (const s of shapes) ts += `    { ${Object.entries(s).map(([k, v]) => `${k}: ${lit(v)}`).join(', ')} },\n`;
  ts += '  ],\n';
}
ts += `} satisfies Record<string, readonly Shape[]>;

export type GlyphName = keyof typeof GLYPHS;
`;
fs.writeFileSync(OUT, ts);
console.log(`${Object.keys(glyphs).length} glyphs → ${path.relative(process.cwd(), OUT)} (${ts.length} chars)`);
